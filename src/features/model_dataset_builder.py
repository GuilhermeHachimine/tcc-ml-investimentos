import pandas as pd

from src.features.feature_engineering import FeatureEngineer
from src.features.target_builder import TargetBuilder
from src.utils.config import CONFIG


class ModelDatasetBuilder:
    """
    Build the final modeling dataset by combining features and target.
    """

    def __init__(self) -> None:
        self.feature_engineer = FeatureEngineer()
        self.target_builder = TargetBuilder()
        self.curated_data_dir = CONFIG.curated_data_dir

    def build_model_dataset(
        self,
        stock_prices: pd.DataFrame,
        benchmark_prices: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Build modeling-ready dataset.

        Returns
        -------
        pd.DataFrame
            Dataset containing features, target and metadata columns.
        """
        features_df = self.feature_engineer.build_features(
            dataframe=stock_prices,
        )

        target_df = self.target_builder.build_monthly_target(
            stock_prices=stock_prices,
            benchmark_prices=benchmark_prices,
        )

        selected_target_columns = [
            "date",
            "ticker",
            "future_stock_return",
            "future_benchmark_return",
            "target",
        ]

        model_df = features_df.merge(
            target_df[selected_target_columns],
            on=["date", "ticker"],
            how="inner",
        )

        model_df = self._select_model_columns(model_df)
        model_df = self._remove_invalid_rows(model_df)

        return model_df

    def _select_model_columns(
        self,
        dataframe: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Select only modeling-related columns.
        """
        selected_columns = [
            "date",
            "ticker",
            "adj_close",
            "volume",
            "daily_return",
            "return_5d",
            "return_21d",
            "return_63d",
            "volatility_21d",
            "volatility_63d",
            "moving_average_21d",
            "moving_average_63d",
            "distance_to_ma_21d",
            "distance_to_ma_63d",
            "average_volume_21d",
            "relative_volume_21d",
            "future_stock_return",
            "future_benchmark_return",
            "target",
        ]

        return dataframe[selected_columns]

    def _remove_invalid_rows(
        self,
        dataframe: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Remove rows with missing values generated by rolling windows and target shift.
        """
        return dataframe.dropna().reset_index(drop=True)

    def save_model_dataset(
        self,
        dataframe: pd.DataFrame,
        file_stem: str = "model_dataset",
    ) -> dict[str, str]:
        """
        Save curated model dataset in Parquet and CSV formats.
        """
        self.curated_data_dir.mkdir(parents=True, exist_ok=True)

        parquet_path = self.curated_data_dir / f"{file_stem}.parquet"
        csv_path = self.curated_data_dir / f"{file_stem}.csv"

        dataframe.to_parquet(parquet_path, index=False)
        dataframe.to_csv(csv_path, index=False)

        return {
            "parquet": str(parquet_path),
            "csv": str(csv_path),
        }

    def build_and_save_from_raw(
        self,
    ) -> tuple[pd.DataFrame, dict[str, str]]:
        """
        Build and save the model dataset using raw Parquet files.
        """
        stock_prices = pd.read_parquet(CONFIG.raw_data_dir / "ibov_prices.parquet")

        benchmark_prices = pd.read_parquet(
            CONFIG.raw_data_dir / "ibovespa_benchmark.parquet"
        )

        model_dataset = self.build_model_dataset(
            stock_prices=stock_prices,
            benchmark_prices=benchmark_prices,
        )

        output_paths = self.save_model_dataset(
            dataframe=model_dataset,
        )

        return model_dataset, output_paths
